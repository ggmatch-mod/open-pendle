#!/usr/bin/env node
// Build the checked-in, constructor-only deploy transaction. No external npm
// contracts/packages or on-chain template registration are used.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = join(dirname(fileURLToPath(import.meta.url)), '../..')
const root = join(repo, 'contracts/oracle-sy')
const target = join(repo, 'app/src/generated/oracleSyArtifact.ts')
const check = process.argv.includes('--check')
execFileSync('forge', ['build', '--root', root, '--skip', 'test'], { stdio: 'inherit' })

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name)
    return entry.isDirectory() ? walk(path) : path.endsWith('.sol') ? [path] : []
  })
}
const hash = createHash('sha256')
for (const path of [join(root, 'foundry.toml'), ...walk(join(root, 'src')), ...walk(join(root, 'vendor'))].sort()) {
  hash.update(relative(root, path)).update('\0').update(readFileSync(path)).update('\0')
}
const sourceHash = hash.digest('hex')
function artifact(name) { return JSON.parse(readFileSync(join(root, 'out', `${name}.sol`, `${name}.json`), 'utf8')) }
const bootstrap = artifact('OracleSyBootstrap')
const oracle = artifact('ShiftReceiptOracle')
const sy = artifact('ShiftOracleSY')
const bytecode = bootstrap.bytecode.object.startsWith('0x') ? bootstrap.bytecode.object : `0x${bootstrap.bytecode.object}`
if (bytecode.includes('__') || bytecode.length < 100 || (bytecode.length - 2) / 2 > 48_000) throw new Error('Invalid or oversized bootstrap bytecode')
const generated = [
  '// GENERATED by scripts/build-oracle-sy.mjs. Do not edit by hand.',
  '// Solidity 0.8.26; optimizer 200; viaIR; Paris EVM; metadata disabled.',
  `// Source SHA-256: ${sourceHash}`,
  `export const ORACLE_SY_SOURCE_HASH = '${sourceHash}' as const`,
  `export const ORACLE_SY_BOOTSTRAP_ABI = ${JSON.stringify(bootstrap.abi, null, 2)} as const`,
  `export const ORACLE_SY_ORACLE_ABI = ${JSON.stringify(oracle.abi, null, 2)} as const`,
  `export const ORACLE_SY_ABI = ${JSON.stringify(sy.abi, null, 2)} as const`,
  `export const ORACLE_SY_BOOTSTRAP_BYTECODE = '${bytecode}' as const`,
  '',
].join('\n')
if (check) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Oracle SY artifact differs. Run npm run build:oracle-sy and review the change.')
  console.log(`Oracle SY artifact verified (${(bytecode.length - 2) / 2} creation bytes).`)
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, generated)
  console.log(`Generated ${relative(repo, target)} (${(bytecode.length - 2) / 2} creation bytes).`)
}
